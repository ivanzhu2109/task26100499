// Package reuse 实现学术查重的连续复用片段定位。
//
// 上层通过两类操作使用本库：
//
//   - Build：整批构建语料，来源文档（唯一正整数编号 + UTF-8 纯文本）
//     被切词、索引后写入本地文件，构建完成后语料只读；
//   - Open / Query：加载语料，在待查文本中定位连续复用证据。
//
// 词定义为最长连续 ASCII 英文字母串，匹配忽略大小写，其余字符均为
// 分隔符且不影响逐词匹配。对待查文本的每个词起点，求能在某一份来源
// 内逐词连续出现的最长片段（不足 8 词不形成证据，匹配不跨文档边界）；
// 并列时先取最长、再取来源编号最小、再取来源内起始位置最早。最终丢弃
// 待查区间被其他候选严格包含的证据，坐标以 Unicode 码点计、左闭右开。
//
// 实现上，语料词序列（文档间以保留词 ID 分隔）建立后缀数组，
// 查询经双滚动哈希做最长公共前缀二分，候选来源经 SA 序上的
// 区间最小线段树选出，复杂度为每词起点 O(log n · log m)。
